CREATE TABLE fraud_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(100) NOT NULL,
    amount NUMERIC(14, 2) NOT NULL,
    country VARCHAR(100),
    fraud BOOLEAN NOT NULL,
    risk_score INTEGER NOT NULL,
    category VARCHAR(20) NOT NULL,
    CONSTRAINT uk_fraud_result_transaction_id UNIQUE (transaction_id)
);

CREATE TABLE fraud_result_reasons (
    fraud_result_id BIGINT NOT NULL,
    reason VARCHAR(500),
    CONSTRAINT fk_fraud_result_reasons_result
        FOREIGN KEY (fraud_result_id) REFERENCES fraud_result (id)
);
